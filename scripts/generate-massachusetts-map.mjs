import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { geoMercator, geoPath } from 'd3-geo';

const sourceUrl = new URL(
    'https://services8.arcgis.com/o4UVke7qqC8oNJ7j/ArcGIS/rest/services/Massachusetts_Towns_General_Coast/FeatureServer/0/query',
);

sourceUrl.search = new URLSearchParams({
    where: '1=1',
    outFields: 'TOWN,TOWN_ID,COUNTY',
    returnGeometry: 'true',
    outSR: '4326',
    geometryPrecision: '4',
    maxAllowableOffset: '0.002',
    f: 'geojson',
}).toString();

const response = await fetch(sourceUrl);

if (!response.ok) {
    throw new Error(`MassGIS request failed with ${response.status} ${response.statusText}`);
}

const featureCollection = await response.json();

if (!Array.isArray(featureCollection.features) || featureCollection.features.length !== 351) {
    throw new Error(`Expected 351 Massachusetts municipalities, received ${featureCollection.features?.length ?? 0}`);
}

function coordinatePairs(value) {
    if (Array.isArray(value) && typeof value[0] === 'number' && typeof value[1] === 'number') {
        return [value];
    }

    return Array.isArray(value) ? value.flatMap(coordinatePairs) : [];
}

function mapCoordinates(value, transform) {
    if (Array.isArray(value) && typeof value[0] === 'number' && typeof value[1] === 'number') {
        return transform(value);
    }

    return Array.isArray(value) ? value.map((item) => mapCoordinates(item, transform)) : value;
}

const allCoordinates = featureCollection.features.flatMap((feature) =>
    coordinatePairs(feature.geometry.coordinates),
);
const rawProjection = geoMercator().scale(1).translate([0, 0]);
const rawPoints = allCoordinates.map((coordinate) => rawProjection(coordinate));
const rawX = rawPoints.map((point) => point[0]);
const rawY = rawPoints.map((point) => point[1]);
const rawBounds = {
    minX: Math.min(...rawX),
    maxX: Math.max(...rawX),
    minY: Math.min(...rawY),
    maxY: Math.max(...rawY),
};
const scale = Math.min(
    384 / (rawBounds.maxX - rawBounds.minX),
    234 / (rawBounds.maxY - rawBounds.minY),
);
const projection = geoMercator().scale(scale).translate([0, 0]);
const scaledPoints = allCoordinates.map((coordinate) => projection(coordinate));
const scaledX = scaledPoints.map((point) => point[0]);
const scaledY = scaledPoints.map((point) => point[1]);
const scaledBounds = {
    minX: Math.min(...scaledX),
    maxX: Math.max(...scaledX),
    minY: Math.min(...scaledY),
    maxY: Math.max(...scaledY),
};
projection.translate([
    8 + (384 - (scaledBounds.maxX - scaledBounds.minX)) / 2 - scaledBounds.minX,
    8 + (234 - (scaledBounds.maxY - scaledBounds.minY)) / 2 - scaledBounds.minY,
]);

const projectedFeatures = featureCollection.features.map((feature) => ({
    ...feature,
    geometry: {
        ...feature.geometry,
        coordinates: mapCoordinates(feature.geometry.coordinates, (coordinate) => projection(coordinate)),
    },
}));
const path = geoPath(null).digits(2);
const bostonPoint = projection([-71.0589, 42.3601]);

if (!bostonPoint) {
    throw new Error('Unable to project the Boston map marker.');
}

const towns = projectedFeatures
    .map((feature) => {
        const town = String(feature.properties?.TOWN ?? '').toUpperCase();
        const mapPath = path(feature);

        if (!town || !mapPath) {
            throw new Error('MassGIS returned a municipality without a town name or geometry.');
        }

        return {
            id: town.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-').replaceAll(/(^-|-$)/g, ''),
            town,
            path: mapPath,
        };
    })
    .sort((a, b) => a.town.localeCompare(b.town));

const output = `// Generated by npm run map:generate from the MassGIS municipalities service.\n` +
    `// Source: ${sourceUrl.origin}${sourceUrl.pathname}\n\n` +
    `export const massachusettsMapViewBox = '165 0 235 250';\n\n` +
    `export const massachusettsTowns = ${JSON.stringify(towns)} as const;\n\n` +
    `export const bostonMapPoint = ${JSON.stringify(bostonPoint.map((value) => Number(value.toFixed(2))))} as const;\n`;

const outputPath = resolve(process.cwd(), 'src/lib/massachusetts-map.generated.ts');
await writeFile(outputPath, output, 'utf8');

console.log(`Generated ${towns.length} municipal paths at ${outputPath}`);
